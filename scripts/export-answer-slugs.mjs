#!/usr/bin/env bun
/**
 * Exports the canonical answer-slug allowlist for the oracle-proxy Worker.
 *
 * The Worker runtime cannot import `$lib`, so the registry set is generated
 * into `apps/workers/oracle-proxy/src/answer-slugs.ts` and checked in.
 * Re-run whenever answer slugs are added, renamed, or retired:
 *
 *   bun scripts/export-answer-slugs.mjs
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getAllAnswerSlugs } from "../apps/web/src/lib/content/answers/registry";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "apps/workers/oracle-proxy/src/answer-slugs.ts");

const slugs = [...getAllAnswerSlugs()].sort();
// Trailing comma keeps the output byte-identical to `prettier --write`, so
// `--check` stays green after formatting and Prettier stays green too.
const slugList = JSON.stringify(slugs, null, 2).replace(/\n\]$/, ",\n]");
const body = `// AUTO-GENERATED by scripts/export-answer-slugs.mjs — do not edit.\n// Regenerate with: bun scripts/export-answer-slugs.mjs\n// Source of truth: apps/web/src/lib/content/answers/registry.ts\n\nexport const ANSWER_SLUGS: ReadonlySet<string> = new Set(${slugList});\n\nexport function isKnownAnswerSlug(slug: string): boolean {\n  return ANSWER_SLUGS.has(slug);\n}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8") : null;
  if (current !== body) {
    console.error(
      `answer-slugs.ts is stale (${slugs.length} slugs in registry). Regenerate with: bun scripts/export-answer-slugs.mjs`,
    );
    process.exit(1);
  }
  console.log(`answer-slugs.ts is in sync (${slugs.length} slugs).`);
} else {
  writeFileSync(outPath, body);
  console.log(`Wrote ${slugs.length} answer slugs to ${outPath}`);
}
