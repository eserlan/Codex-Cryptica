import { describe, expect, it } from "vitest";
import {
  GenerationInputHistoryStore,
  GenerationNameHistoryStore,
  GenerationSeedHistoryStore,
  summarizeResolvedInputs,
  formatRecentInputsNote,
} from "./generation-input-history";

function memoryStorage() {
  const map = new Map<string, string>();
  return {
    getItem: (key: string) => map.get(key) ?? null,
    setItem: (key: string, value: string) => {
      map.set(key, value);
    },
    removeItem: (key: string) => {
      map.delete(key);
    },
  };
}

describe("GenerationInputHistoryStore", () => {
  it("starts empty for any generator id", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    expect(store.recent("npc")).toEqual([]);
  });

  it("records summaries most-recent-first, keyed per generator id", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    store.record("npc", "genre: Cyberpunk, role: Fixer");
    store.record("npc", "genre: Classic Fantasy, role: Innkeeper");
    store.record("faction", "genre: Cosmic Horror");
    expect(store.recent("npc")).toEqual([
      "genre: Classic Fantasy, role: Innkeeper",
      "genre: Cyberpunk, role: Fixer",
    ]);
    expect(store.recent("faction")).toEqual(["genre: Cosmic Horror"]);
  });

  it("de-duplicates and moves a repeated summary to the front", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    store.record("quest", "genre: Fantasy");
    store.record("quest", "genre: Sci-Fi");
    store.record("quest", "genre: Fantasy");
    expect(store.recent("quest")).toEqual(["genre: Fantasy", "genre: Sci-Fi"]);
  });

  it("caps history at 3 entries per generator", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    for (const s of ["A", "B", "C", "D", "E"]) store.record("world", s);
    expect(store.recent("world")).toEqual(["E", "D", "C"]);
  });

  it("ignores blank or undefined summaries", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    store.record("npc", undefined);
    store.record("npc", "   ");
    expect(store.recent("npc")).toEqual([]);
  });

  it("keeps generator ids independent", () => {
    const store = new GenerationInputHistoryStore(memoryStorage());
    store.record("npc", "genre: Fantasy");
    expect(store.recent("faction")).toEqual([]);
  });
});

describe("summarizeResolvedInputs", () => {
  it("joins short string fields as key: value pairs", () => {
    const summary = summarizeResolvedInputs({
      genre: "Cyberpunk / Corporate",
      tone: "Bleak",
      threatScale: "Global",
    });
    expect(summary).toBe(
      "genre: Cyberpunk / Corporate, tone: Bleak, threatScale: Global",
    );
  });

  it("excludes keys ending in name (case-insensitive)", () => {
    const summary = summarizeResolvedInputs({
      genre: "Fantasy",
      villainName: "Corvin Ashmere, the Quiet Hand",
      questName: "The Bell Beneath Blackwater",
    });
    expect(summary).toBe("genre: Fantasy");
  });

  it("excludes campaignContext and context fields", () => {
    const summary = summarizeResolvedInputs({
      genre: "Fantasy",
      campaignContext: "a coastal town hiding a drowned cult",
      context: "some freeform world context",
    });
    expect(summary).toBe("genre: Fantasy");
  });

  it("excludes non-string and overly long values", () => {
    const summary = summarizeResolvedInputs({
      genre: "Fantasy",
      count: 5,
      longField: "x".repeat(61),
    });
    expect(summary).toBe("genre: Fantasy");
  });

  it("returns an empty string when nothing qualifies", () => {
    expect(summarizeResolvedInputs({ villainName: "X" })).toBe("");
  });
});

describe("formatRecentInputsNote", () => {
  it("returns an empty string when there's no history", () => {
    expect(formatRecentInputsNote([])).toBe("");
  });

  it("formats a note listing recent summaries", () => {
    const note = formatRecentInputsNote(["genre: Fantasy", "genre: Sci-Fi"]);
    expect(note).toContain(
      "Recently generated by this tool this session, most recent first",
    );
    expect(note).toContain("genre: Fantasy | genre: Sci-Fi");
  });
});

describe("GenerationSeedHistoryStore", () => {
  const seed = (premise: string, titleIdea = "A Title") => ({
    premise,
    stake: "a stake",
    setting: "a setting",
    distinctiveElement: "a detail",
    titleIdea,
  });

  it("starts empty for a generator with no accepted seeds", () => {
    const store = new GenerationSeedHistoryStore(memoryStorage());
    expect(store.recent("mystery-investigation")).toEqual([]);
  });

  it("records accepted seeds most-recent-first, keyed per generator", () => {
    const store = new GenerationSeedHistoryStore(memoryStorage());
    store.record("mystery-investigation", seed("First premise"));
    store.record("mystery-investigation", seed("Second premise"));
    store.record("one-shot", seed("Other generator"));
    expect(store.recent("mystery-investigation").map((s) => s.premise)).toEqual(
      ["Second premise", "First premise"],
    );
    expect(store.recent("one-shot").map((s) => s.premise)).toEqual([
      "Other generator",
    ]);
  });

  it("moves a repeated premise to the front rather than duplicating it", () => {
    const store = new GenerationSeedHistoryStore(memoryStorage());
    store.record("mystery-investigation", seed("Same premise", "One"));
    store.record("mystery-investigation", seed("Other premise"));
    store.record("mystery-investigation", seed("Same premise", "Two"));
    const recent = store.recent("mystery-investigation");
    expect(recent.map((s) => s.premise)).toEqual([
      "Same premise",
      "Other premise",
    ]);
    expect(recent[0].titleIdea).toBe("Two");
  });

  it("caps history at five seeds per generator", () => {
    const store = new GenerationSeedHistoryStore(memoryStorage());
    for (const premise of ["A", "B", "C", "D", "E", "F"]) {
      store.record("mystery-investigation", seed(premise));
    }
    expect(store.recent("mystery-investigation").map((s) => s.premise)).toEqual(
      ["F", "E", "D", "C", "B"],
    );
  });

  it("ignores missing, incomplete or blank seeds", () => {
    const store = new GenerationSeedHistoryStore(memoryStorage());
    store.record("mystery-investigation", null);
    store.record("mystery-investigation", undefined);
    store.record("mystery-investigation", {
      premise: "only a premise",
    } as never);
    store.record("mystery-investigation", seed("   "));
    expect(store.recent("mystery-investigation")).toEqual([]);
  });

  it("drops malformed entries already in storage", () => {
    const storage = memoryStorage();
    storage.setItem(
      "GENERATION_SEED_HISTORY",
      JSON.stringify({
        "mystery-investigation": [seed("Kept"), { premise: "broken" }, "text"],
      }),
    );
    const store = new GenerationSeedHistoryStore(storage);
    expect(store.recent("mystery-investigation").map((s) => s.premise)).toEqual(
      ["Kept"],
    );
  });

  it("survives unreadable or unwritable storage", () => {
    const broken = {
      getItem: () => {
        throw new Error("denied");
      },
      setItem: () => {
        throw new Error("quota");
      },
      removeItem: () => {},
    };
    const store = new GenerationSeedHistoryStore(broken);
    expect(store.recent("mystery-investigation")).toEqual([]);
    expect(() =>
      store.record("mystery-investigation", seed("Lost")),
    ).not.toThrow();
  });
});

describe("GenerationNameHistoryStore", () => {
  it("starts empty for any generator id", () => {
    const store = new GenerationNameHistoryStore(memoryStorage());
    expect(store.recent("mystery-investigation")).toEqual([]);
  });

  it("records names most-recent-first and de-duplicates case-insensitively", () => {
    const store = new GenerationNameHistoryStore(memoryStorage());
    store.record("mystery-investigation", ["Orsik Pell", "Kaelen Voss"]);
    store.record("mystery-investigation", ["orsik pell", "Mara Vane"]);
    expect(store.recent("mystery-investigation")).toEqual([
      "orsik pell",
      "Mara Vane",
      "Kaelen Voss",
    ]);
  });

  it("trims whitespace and ignores empty names", () => {
    const store = new GenerationNameHistoryStore(memoryStorage());
    store.record("mystery-investigation", ["  ", "  Corvin Ash  ", ""]);
    expect(store.recent("mystery-investigation")).toEqual(["Corvin Ash"]);
  });

  it("caps history at 20 names per generator", () => {
    const store = new GenerationNameHistoryStore(memoryStorage());
    const names = Array.from({ length: 25 }, (_, i) => `Person ${i + 1}`);
    store.record("mystery-investigation", names);
    const recent = store.recent("mystery-investigation");
    expect(recent).toHaveLength(20);
    expect(recent[0]).toBe("Person 1");
    expect(recent[19]).toBe("Person 20");
  });

  it("keeps generator ids independent", () => {
    const store = new GenerationNameHistoryStore(memoryStorage());
    store.record("mystery-investigation", ["Orsik Pell"]);
    expect(store.recent("npc")).toEqual([]);
  });

  it("survives unreadable or unwritable storage", () => {
    const broken = {
      getItem: () => {
        throw new Error("denied");
      },
      setItem: () => {
        throw new Error("quota");
      },
      removeItem: () => {},
    };
    const store = new GenerationNameHistoryStore(broken);
    expect(store.recent("mystery-investigation")).toEqual([]);
    expect(() =>
      store.record("mystery-investigation", ["Orsik Pell"]),
    ).not.toThrow();
  });
});
