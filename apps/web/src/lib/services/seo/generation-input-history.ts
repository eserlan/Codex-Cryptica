import type { ConceptSeed } from "generator-engine";
import {
  browserSessionStorage,
  type StorageLike,
} from "$lib/utils/runtime-deps";

const STORAGE_KEY = "GENERATION_INPUT_HISTORY";
const MAX_HISTORY_PER_GENERATOR = 3;

/**
 * Reads a per-generator record from storage, keeping only the entries that
 * pass `keep`. Unreadable or malformed storage reads as empty.
 */
function readHistory<T>(
  storage: StorageLike,
  key: string,
  keep: (value: unknown) => value is T,
): Record<string, T[]> {
  try {
    const raw = storage.getItem(key);
    const parsed: unknown = raw ? JSON.parse(raw) : {};
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
      return {};
    }
    const result: Record<string, T[]> = {};
    for (const [generatorId, value] of Object.entries(parsed)) {
      if (Array.isArray(value)) result[generatorId] = value.filter(keep);
    }
    return result;
  } catch {
    return {};
  }
}

const isString = (value: unknown): value is string => typeof value === "string";

/**
 * Tracks the resolved input options (genre, tone, scope, etc.) of recent
 * generations per generator this browser session, so each generator's
 * prompt can be nudged to vary away from a recently-used combination instead
 * of only being asked for variety in the abstract (#2325 follow-up).
 */
export class GenerationInputHistoryStore {
  private storage: StorageLike;

  constructor(storage: StorageLike = browserSessionStorage) {
    this.storage = storage;
  }

  private loadAll(): Record<string, string[]> {
    return readHistory(this.storage, STORAGE_KEY, isString);
  }

  /** Most recent summaries first, oldest last, for the given generator id. */
  recent(generatorId: string): string[] {
    return this.loadAll()[generatorId] ?? [];
  }

  record(generatorId: string, summary: string | undefined): void {
    const trimmed = summary?.trim();
    if (!trimmed) return;
    const all = this.loadAll();
    const existing = all[generatorId] ?? [];
    all[generatorId] = [
      trimmed,
      ...existing.filter((s) => s !== trimmed),
    ].slice(0, MAX_HISTORY_PER_GENERATOR);
    try {
      this.storage.setItem(STORAGE_KEY, JSON.stringify(all));
    } catch {
      // Best-effort — storage may be unavailable (private mode, quota).
    }
  }
}

export const generationInputHistoryStore = new GenerationInputHistoryStore();

/**
 * Builds a short "genre: X, tone: Y" style summary from any generator's
 * `resolved` options object. Excludes generated-name fields (keys ending in
 * "name", e.g. villainName/questName — identifiers, not input choices) and
 * freeform context fields (campaignContext/context — user-written prose, not
 * a choice worth nudging variety on).
 */
export function summarizeResolvedInputs(resolved: object): string {
  return Object.entries(resolved)
    .filter(
      ([key, value]) =>
        typeof value === "string" &&
        value.length > 0 &&
        value.length < 60 &&
        !/name$/i.test(key) &&
        key !== "campaignContext" &&
        key !== "context",
    )
    .map(([key, value]) => `${key}: ${value as string}`)
    .join(", ");
}

/**
 * Formats the "vary away from recent generations" prompt note. Returns an
 * empty string when there's no history yet, so callers can unconditionally
 * append it to a sessionContext string.
 */
export function formatRecentInputsNote(
  recentInputs: readonly string[],
): string {
  if (recentInputs.length === 0) return "";
  return `\nRecently generated by this tool this session, most recent first (vary your choices away from repeating the same combination unless the provided context specifically calls for it): ${recentInputs.join(" | ")}`;
}

const SEED_STORAGE_KEY = "GENERATION_SEED_HISTORY";
const MAX_SEEDS_PER_GENERATOR = 5;

const SEED_FIELDS = [
  "premise",
  "stake",
  "setting",
  "distinctiveElement",
  "titleIdea",
] as const;

function isConceptSeed(value: unknown): value is ConceptSeed {
  if (!value || typeof value !== "object" || Array.isArray(value)) return false;
  const record = value as Record<string, unknown>;
  return SEED_FIELDS.every(
    (field) => typeof record[field] === "string" && record[field].trim() !== "",
  );
}

/**
 * The case seeds a generator accepted recently this session, most recent
 * first, so the next seed stage can avoid repeating them. Session-scoped, like
 * the input history above.
 */
export class GenerationSeedHistoryStore {
  private storage: StorageLike;

  constructor(storage: StorageLike = browserSessionStorage) {
    this.storage = storage;
  }

  private loadAll(): Record<string, ConceptSeed[]> {
    return readHistory(this.storage, SEED_STORAGE_KEY, isConceptSeed);
  }

  recent(generatorId: string): ConceptSeed[] {
    return this.loadAll()[generatorId] ?? [];
  }

  record(generatorId: string, seed: ConceptSeed | null | undefined): void {
    if (!isConceptSeed(seed)) return;
    const all = this.loadAll();
    const existing = all[generatorId] ?? [];
    all[generatorId] = [
      seed,
      ...existing.filter((past) => past.premise !== seed.premise),
    ].slice(0, MAX_SEEDS_PER_GENERATOR);
    try {
      this.storage.setItem(SEED_STORAGE_KEY, JSON.stringify(all));
    } catch {
      // Best-effort: storage may be unavailable (private mode, quota).
    }
  }
}

export const generationSeedHistoryStore = new GenerationSeedHistoryStore();

const NAME_STORAGE_KEY = "GENERATION_NAME_HISTORY";
const MAX_NAMES_PER_GENERATOR = 20;

/**
 * Tracks names generated recently this session (per generator), so subsequent
 * runs discourage immediately reusing the same culprit or suspect names.
 */
export class GenerationNameHistoryStore {
  private storage: StorageLike;

  constructor(storage: StorageLike = browserSessionStorage) {
    this.storage = storage;
  }

  private loadAll(): Record<string, string[]> {
    return readHistory(this.storage, NAME_STORAGE_KEY, isString);
  }

  recent(generatorId: string): string[] {
    return this.loadAll()[generatorId] ?? [];
  }

  record(generatorId: string, names: readonly string[]): void {
    const valid = names
      .map((name) => name.trim())
      .filter((name) => name.length > 0);
    if (!valid.length) return;
    const all = this.loadAll();
    const existing = all[generatorId] ?? [];
    const seen = new Set<string>();
    const merged: string[] = [];
    for (const name of [...valid, ...existing]) {
      const lower = name.toLowerCase();
      if (!seen.has(lower)) {
        seen.add(lower);
        merged.push(name);
      }
    }
    all[generatorId] = merged.slice(0, MAX_NAMES_PER_GENERATOR);
    try {
      this.storage.setItem(NAME_STORAGE_KEY, JSON.stringify(all));
    } catch {
      // Best-effort: storage may be unavailable.
    }
  }
}

export const generationNameHistoryStore = new GenerationNameHistoryStore();
